-- ============================================================================
-- 迁移：把 NPC 的「报告腔」改成角色自己的口吻（2026-09-21）
--
-- 问题：NPC 的回答听起来像一份调查报告 / 一个法律顾问，而不是一个记得某些事、
--       对另一些事不确定的人。玩家的原话：
--         「我只能给你一个谨慎的框架……」「我不把『记得』当作证据……」
--         「我的职责是……」「我能确认的只有……」
--       根因有三处，必须一起改，只改提示词是不够的：
--         1) PromptBuilder 的 system 提示词（已改：改角色扮演指令）
--         2) AgentService.fallbackNpc 的降级文案（已改：口语化短句）
--         3) **npc_knowledge.content 本身就是用方法论口吻写的**（本文件修的就是这个）
--       第 3 条尤其关键：知识条目是喂给模型的「这个角色记得什么」，
--       如果原文写成「应先核对视频时间码、电梯控制逻辑和公开版本是否经过剪辑」，
--       模型复述出来必然还是顾问腔。
--
-- 范围：全部 7 名 NPC 的 17 条知识 + 5 条开场白。
--       用户要求「重点重写 CASE-001 的米娅·托雷斯」，但提示词改动是全局的，
--       只改 CASE-001 会让另外两个案件的角色语气明显不一致，所以一起改。
--
-- 原则：**事实一条都不改，只改说话方式**。
--       入住/失踪日期、电梯片段、法医结论、供水发现顺序、Z340 破解、跨警区编号
--       等事实全部保留，只是从第三人称的公开摘要改成第一人称、碎片化、带犹豫的记忆口吻。
--
-- 为什么必须写这个文件：data.sql 只管「全新安装」。已存在的库不会被重跑 data.sql，
-- 不写迁移，老库和新库的 NPC 台词就会分叉。
--
-- 幂等：每条 UPDATE 都带 `WHERE id = ? AND <旧值>`。重复执行时旧值已不存在 → 影响 0 行，
--       不会出错、也不会有副作用。
--
-- 用法：
--   mysql --host=127.0.0.1 --port=3307 --user=root --database=mindtrace \
--         --default-character-set=utf8mb4 \
--         < database/migration-2026-09-21-npc-voice.sql
-- ============================================================================

USE mindtrace;

-- ---------------------------------------------------------------------------
-- 1) npc：开场白与性格描述
--    开场白会作为对话框里的第一条消息显示，是玩家对角色语气的第一印象，
--    所以它也必须是人话，不能是「我只能根据值班记录和公开资料回答」。
--    伊芙琳（id=4）与周师傅（id=3）的开场白本来就是角色口吻，不动。
-- ---------------------------------------------------------------------------
UPDATE npc
SET greeting    = '嗯……你也是为了那件事来的吧。值班记录我这儿有一份，你想问哪段？',
    personality = '谨慎、克制、话不多，对媒体叙事保持警惕'
WHERE id = 1
  AND greeting = '我只能根据值班记录和公开资料回答。你想核对哪个时间点？';

UPDATE npc
SET greeting = '先别急着下结论。你手上的东西，哪些是公开事实、哪些只是传闻，先分一分，我们再聊。'
WHERE id = 2
  AND greeting = '先别急着给案件下结论。把你的线索按来源类型分开，我们再谈。';

UPDATE npc
SET greeting = '人物关系我可以帮你理，但“曾被询问过”不等于有罪，这两件事别混。'
WHERE id = 5
  AND greeting = '可以做人物关系判断，但不能把“曾被询问”写成“有罪”。';

UPDATE npc
SET greeting = '密码能说明文本是怎么写的，说明不了是谁写的。你想看哪一段？'
WHERE id = 6
  AND greeting = '密码能证明文本结构，不能单独证明写信者身份。';

UPDATE npc
SET greeting = '这几个警区各写各的时间格式，看着头疼。要对比的话，得先把日期时间对齐。'
WHERE id = 7
  AND greeting = '不同警区的时间格式并不一致，先把日期和时间统一。';

